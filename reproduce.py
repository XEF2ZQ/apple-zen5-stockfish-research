"""Regenerate article arithmetic and SVG from the recorded inputs. No hardware tests."""
import json
from pathlib import Path
from html import escape

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / "benchmarks.json").read_text(encoding="utf-8"))
pm = json.loads((ROOT / "passmark-m5-pro.json").read_text(encoding="utf-8"))
selected = next(s for s in pm["submissions"] if s["id"] == pm["selected_id"])
for metric in ("cpu_mark", "integer", "fp"):
    assert selected[metric] == max(s[metric] for s in pm["submissions"]), metric
assert pm["cpu"] == "Apple M5 Pro 18 Core"
sf = {r["cpu"]: r["value"] for r in data["stockfish_17_1"]}
m4 = data["historical_m4_passmark_average"]
q4 = 12 * 4 * 4.5 + 4 * 2 * 2.6
q5 = 6 * 8 * 4.6 + 12 * 4 * 4.3
lines = [
    "# Calculation audit", "",
    "Generated by reproduce.py. These calculations do not reproduce physical CPU tests.", "",
    "| Quantity | Expression / result |", "|---|---|"
]
for a, b in [
    ("Ryzen 9 9950X3D", "Ryzen 9 9950X"),
    ("Ryzen 9 9950X3D", "Core Ultra 7 270K Plus"),
    ("Ryzen 9 9950X3D", "Core Ultra 9 285K"),
    ("Core Ultra 7 270K Plus", "Core Ultra 9 285K")]:
    ratio = sf[a] / sf[b]
    lines.append(f"| Stockfish: {a} / {b} | {ratio:.6f}x; {(ratio-1)*100:.3f}% |")
for metric in ("integer", "fp"):
    ratio = selected[metric] / m4[metric]
    lines.append(f"| Selected M5 Pro {metric} / historical M4 average (asymmetric) | {ratio:.6f}x; {(ratio-1)*100:.3f}% |")
lines.extend([
    f"| FP reconstruction Q4 | {q4:.3f} |",
    f"| FP reconstruction Q5 | {q5:.3f} |",
    f"| FP modeled ratio | {q5/q4:.6f}x; {(q5/q4-1)*100:.3f}% |",
    f"| Selected observed ratio / modeled ratio | {selected['fp']/m4['fp']/(q5/q4):.6f}x |",
    f"| Nominal M5 ALU count / Zen 5 | {(6*8+12*8)/(16*6):.6f}x |",
    f"| With seven-wide secondary admission | {(6*8+12*7)/(16*6):.6f}x |",
    f"| Conditional reported Apple build throughput | {233/192:.6f}x; {(233/192-1)*100:.3f}% |",
    f"| Conditional reported Apple time reduction | {(1-192/233)*100:.3f}% |", "",
    "Highest means highest within the five identified public submissions inspected, not an exhaustive all-time record.",
    "M5 Pro maxima versus an M4 average are asymmetric; benchmark versions and clock conditions are not matched.",
    "Q4/Q5 assume nominal clocks and eligible paths, not clocks measured in the submitted baselines.", ""
])
(ROOT / "CALCULATIONS.md").write_text("\n".join(lines), encoding="utf-8")

parts = ['<svg xmlns="http://www.w3.org/2000/svg" width="1180" height="720" viewBox="0 0 1180 720" role="img" aria-labelledby="title desc">',
'<title id="title">Version-separated public Stockfish and LLVM results</title>',
'<desc id="desc">Public aggregate means, not controlled paired hardware measurements. Apple and PassMark results are excluded.</desc>',
'<rect width="1180" height="720" fill="#f7f9fc"/>',
'<style>text{font-family:Arial,sans-serif;fill:#14213d}.title{font-size:26px;font-weight:700}.sub{font-size:15px}.label{font-size:17px}.value{font-size:17px;font-weight:700}.note{font-size:14px}</style>',
'<text x="34" y="44" class="title">One processor ranking is not a universal architecture ranking</text>',
'<text x="34" y="72" class="sub">Version-specific public aggregate means • source review: 13 November 2026</text>']
for rows, top, title, maxval, divisor, suffix in [
    (data["stockfish_17_1"], 124, "Stockfish 17.1 • million nodes/s • higher is better", 45, 1e6, "M"),
    (data["llvm_21_1_ninja"], 408, "LLVM 21.1 / Ninja • seconds • lower is better", 360, 1, " s")]:
    parts.append(f'<text x="34" y="{top}" class="label" font-weight="700">{escape(title)}</text>')
    for tick in range(0, 5):
        x = 300 + 720 * tick / 4
        parts.append(f'<line x1="{x}" x2="{x}" y1="{top+32}" y2="{top+221}" stroke="#dae0e9"/>')
        parts.append(f'<text x="{x}" y="{top+244}" class="note" text-anchor="middle">{maxval*tick/4:g}</text>')
    for i, row in enumerate(rows):
        y = top + 55 + i * 49
        value = row["value"] / divisor
        width = value / maxval * 720
        color = "#6e45c2" if "AMD" in row["cpu"] or "Ryzen" in row["cpu"] else "#146da8"
        parts.append(f'<text x="282" y="{y+7}" class="label" text-anchor="end">{escape(row["cpu"])}</text>')
        parts.append(f'<rect x="300" y="{y-13}" width="{width:.2f}" height="28" rx="4" fill="{color}"/>')
        label = f"{value:.3f}M" if divisor != 1 else f"{value:g} s"
        parts.append(f'<text x="{310+width:.2f}" y="{y+7}" class="value">{label}</text>')
parts.append('<text x="34" y="704" class="note">Heterogeneous submissions; no causal attribution. Error fields and sample counts are retained in the article and JSON.</text>')
parts.append("</svg>")
(ROOT / "verified-results.svg").write_text("\n".join(parts), encoding="utf-8")
print("Validated selected baseline, regenerated CALCULATIONS.md and verified-results.svg")

# Revision examples remain explicitly separate from measured benchmark inputs.
evidence = json.loads((ROOT / "architecture-evidence.json").read_text(encoding="utf-8"))
g = evidence["smt_illustration"]["aggregate_gain"]
assert evidence["smt_illustration"]["per_worker_efficiency"] == g / 2
with (ROOT / "CALCULATIONS.md").open("a", encoding="utf-8") as audit:
    audit.write("\n## Revision examples (not measured application gains)\n\n")
    audit.write(f"- Illustrative SMT aggregate gain: {g:.3f}x, {(g-1)*100:.1f}%.\n")
    audit.write(f"- Average per-worker efficiency: {g/2:.3f}, {g/2*100:.1f}%.\n")
    audit.write(f"- Average per-worker progress reduction: {(1-g/2)*100:.1f}%.\n")
    audit.write("- Byte-dot width ratio: 512/128 = 4; rate ratio is 4*r512/r128.\n")
    audit.write("- One 512-bit start versus four 128-bit starts gives equal byte-product coverage per cycle.\n")
